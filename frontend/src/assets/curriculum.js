// Helper function to retrieve one program by its code.
export const getCurriculumByProgram = (programCode) => {
  return curriculumData[programCode?.toUpperCase()] ?? null;
};

// Helper function to retrieve all program summaries.
export const getAllPrograms = () => {
  return Object.values(curriculumData).map(({ curriculum, ...program }) => ({
    ...program,
    totalSubjects: curriculum.reduce(
      (total, year) =>
        total +
        year.semesters.reduce(
          (count, semester) => count + semester.subjects.length,
          0,
        ),
      0,
    ),
  }));
};

